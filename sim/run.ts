import { writeFileSync } from 'node:fs'
import { runStudy } from './study'
import type { StudyOptions, Summary } from './study'

// Runs the simulation study and writes sim/RESULTS.md. Usage: npm run simulate

const PEOPLE = Number(process.env.PEOPLE ?? 2000)
const SEED = Number(process.env.SEED ?? 20261123)

const cal = (value: number) => Math.round(value).toLocaleString('en-US')
const pct = (value: number) => `${Math.round(value * 100)}%`

function table(summaries: Summary[], days: number[]): string {
  const methods = [...new Set(summaries.map(s => s.method))]
  const lines = [
    `| Method | ${days.map(day => `Week ${day / 7}`).join(' | ')} |`,
    `|---|${days.map(() => '---|').join('')}`,
  ]
  for (const method of methods) {
    const cells = days.map(day => {
      const s = summaries.find(row => row.method === method && row.day === day)!
      return `${cal(s.medianError)} / ${cal(s.p90Error)} (${pct(s.within10)})`
    })
    lines.push(`| ${method} | ${cells.join(' | ')} |`)
  }
  return lines.join('\n')
}

function biasLine(summaries: Summary[], day: number): string {
  return summaries
    .filter(s => s.day === day)
    .map(s => `${s.method} ${s.bias >= 0 ? '+' : '−'}${cal(Math.abs(s.bias))}`)
    .join('; ')
}

function section(title: string, options: StudyOptions, note: string): string {
  const started = Date.now()
  const summaries = runStudy(options)
  const app = summaries.filter(s => s.method === 'Check-in (the app)')
  console.log(`${title}: ${((Date.now() - started) / 1000).toFixed(1)} s`)
  return [
    `### ${title}`,
    '',
    note,
    '',
    table(summaries, [7, 14, 21, 28, 42]),
    '',
    `Share of people whose check-in used their log: ${app.map(s => `week ${s.day / 7} ${pct(s.usedLog)}`).join(', ')}.`,
    '',
    `Average error at week 4 (positive = too high): ${biasLine(summaries, 28)}.`,
    '',
  ].join('\n')
}

const base = { people: PEOPLE, seed: SEED }
const parts = [
  `# Check-in simulation results`,
  '',
  `${PEOPLE.toLocaleString('en-US')} simulated people, seed ${SEED}. Each cell: median error / 90th percentile error in calories a day (share within 10% of the truth).`,
  `Generated by \`npm run simulate\`; see the README for the model.`,
  '',
  section('Main result', base, 'Truth = what they really burned over the last 7 days, in the calories they log.'),
  section('Against real calories', { ...base, realCalories: true }, 'Truth in real calories. Under-logging (0 to 30%) now counts as error for the check-in.'),
  section(
    'Everyone logs everything',
    { ...base, underLoggingMax: 0 },
    'No under-logging, so logged and real calories are the same and the formula is judged on its own error.',
  ),
  section('No water shift at the start', { ...base, waterKgPer500: 0 }, 'Same people without the early glycogen and water drop.'),
  section('Formula twice as far off', { ...base, formulaErrorScale: 2 }, 'Resting energy and activity errors doubled.'),
  section(
    'Burn rises 12% from day 21',
    { ...base, expenditureChange: { day: 21, factor: 1.12 } },
    'Everyone starts moving more on day 21 (a new job or more training), so the truth jumps and the estimate has to follow.',
  ),
]

writeFileSync(new URL('./RESULTS.md', import.meta.url), parts.join('\n'))
console.log(parts.join('\n'))
